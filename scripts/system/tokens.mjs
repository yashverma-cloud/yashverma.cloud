/**
 * Writes src/system/tokens.css from src/system/tokens.mjs, and checks the system's contrast.
 *
 *   node scripts/system/tokens.mjs           write the CSS and print the contrast table
 *   node scripts/system/tokens.mjs --check   write nothing; fail if the CSS is out of date or
 *                                            any text pair is under its WCAG AA minimum
 *
 * `npm run build` runs the check first, so a token change can't ship without its CSS, and no
 * colour can be changed into an unreadable pair.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import {
  colour,
  contrast,
  duration,
  ease,
  fluid,
  font,
  grid,
  layer,
  MEASURE,
  space,
  TEXT_PAIRS,
  type,
  weight,
} from '../../src/system/tokens.mjs';

const OUT = fileURLToPath(new URL('../../src/system/tokens.css', import.meta.url));
const check = process.argv.includes('--check');

const kebab = (s) => s.replace(/([a-z])([A-Z0-9])/g, '$1-$2').toLowerCase();

function css() {
  const lines = [];
  const add = (name, value, note) => lines.push(`  --${name}: ${value};${note ? ` /* ${note} */` : ''}`);

  lines.push('  /* Colour */');
  for (const [name, value] of Object.entries(colour)) add(kebab(name), value);

  lines.push('', '  /* Type */');
  add('font-sans', font.sans);
  add('font-mono', font.mono);
  add('font-deva', font.deva);
  for (const [name, t] of Object.entries(type)) {
    add(`t-${name}`, fluid([t.min, t.max]), `${t.min}px at 360, ${t.max}px at 2560`);
    add(`lh-${name}`, String(t.lh));
    add(`tr-${name}`, `${t.track}em`);
    if (!t.mono) {
      add(`wght-${name}`, String(t.wght));
      add(`wdth-${name}`, `${t.wdth}%`);
    }
  }
  add('measure', MEASURE);

  lines.push('', '  /* Space and grid */');
  for (const [name, range] of Object.entries(space)) add(`space-${name}`, fluid(range));
  add('columns', String(grid.columns));
  add('margin', fluid(grid.margin));
  add('gap', fluid(grid.gap));

  lines.push('', '  /* Line weights */');
  for (const [name, w] of Object.entries(weight)) add(`w-${name}`, `${w}px`);

  lines.push('', '  /* Layers */');
  for (const [name, z] of Object.entries(layer)) add(`z-${name}`, String(z));

  lines.push('', '  /* Motion */');
  for (const [name, c] of Object.entries(ease)) add(`ease-${name}`, `cubic-bezier(${c.join(', ')})`);
  for (const [name, ms] of Object.entries(duration)) add(`dur-${name}`, `${ms}ms`);

  return (
    '/* Generated by scripts/system/tokens.mjs from src/system/tokens.mjs. Edit that file, not this one. */\n\n' +
    `:root {\n${lines.join('\n')}\n}\n`
  );
}

function contrastTable() {
  const rows = TEXT_PAIRS.map((p) => {
    const ratio = contrast(colour[p.fg], colour[p.bg]);
    return { ...p, ratio, ok: ratio >= p.min };
  });
  for (const r of rows) {
    const mark = r.ok ? 'ok  ' : 'FAIL';
    console.log(`  ${mark} ${r.fg.padEnd(6)} on ${r.bg.padEnd(6)} ${r.ratio.toFixed(2).padStart(5)} (min ${r.min}${r.edge ? ', edge' : ''})`);
  }
  return rows.filter((r) => !r.ok);
}

const next = css();
console.log('Contrast (WCAG 2.2 AA):');
const failures = contrastTable();

if (check) {
  let current = '';
  try {
    current = await readFile(OUT, 'utf8');
  } catch {
    /* missing counts as out of date */
  }
  const stale = current !== next;
  if (stale) console.error('\nsrc/system/tokens.css is out of date: run `node scripts/system/tokens.mjs`.');
  if (failures.length) console.error(`\n${failures.length} pair(s) under AA.`);
  process.exit(stale || failures.length ? 1 : 0);
} else {
  await writeFile(OUT, next);
  console.log(`\nWrote ${OUT.slice(OUT.indexOf('src/'))}`);
  if (failures.length) {
    console.error(`${failures.length} pair(s) under AA.`);
    process.exit(1);
  }
}
